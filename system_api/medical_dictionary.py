# 工具函數
# ============================================================================

def is_medical_term(term: str) -> bool:
    """
    判斷是否為醫療專有名詞
    
    Args:
        term: 詞彙
    
    Returns:
        是否為醫療詞彙
    """
    return term in ALL_MEDICAL_TERMS


def get_medical_category(term: str) -> str:
    """
    獲取醫療詞彙的類別
    
    Args:
        term: 詞彙
    
    Returns:
        類別名稱 (disease/procedure/medical_term/professional/department/unknown)
    """
    if term in DISEASES:
        return 'disease'
    elif term in MEDICAL_PROCEDURES:
        return 'procedure'
    elif term in MEDICAL_TERMS:
        return 'medical_term'
    elif term in MEDICAL_PROFESSIONALS:
        return 'professional'
    elif term in MEDICAL_DEPARTMENTS:
        return 'department'
    else:
        return 'unknown'


def is_disease_name(term: str) -> bool:
    """
    判斷是否為疾病名稱（最重要的核心詞）
    
    Args:
        term: 詞彙
    
    Returns:
        是否為疾病名稱
    """
    return term in DISEASES


def is_critical_medical_term(term: str) -> bool:
    """
    判斷是否為關鍵醫療詞彙（疾病或重要檢查/治療）
    
    這些詞彙應該被歸類為核心詞彙（CORE），不應被當作廣泛詞彙
    
    Args:
        term: 詞彙
    
    Returns:
        是否為關鍵醫療詞彙
    """
    return term in DISEASES or term in MEDICAL_PROCEDURES


def get_jieba_custom_words() -> list:
    """
    獲取用於 jieba 自定義詞典的詞彙列表
    
    Returns:
        [(詞彙, 頻率, 標籤), ...]
    """
    custom_words = []
    
    # 疾病名稱（最高優先級）
    for word in DISEASES:
        custom_words.append((word, 10000, 'disease'))
    
    # 醫療檢查與技術（高優先級）
    for word in MEDICAL_PROCEDURES:
        custom_words.append((word, 8000, 'procedure'))
    
    # 其他醫療術語（中優先級）
    for word in MEDICAL_TERMS:
        custom_words.append((word, 5000, 'medical'))
    
    # 專業人員和科別（中優先級）
    for word in MEDICAL_PROFESSIONALS | MEDICAL_DEPARTMENTS:
        custom_words.append((word, 5000, 'medical'))
    
    return custom_words


